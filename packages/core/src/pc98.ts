import { DEFAULT_CONFIG, FS_BIOS_DIR, FS_FONT, toIni, type MachineConfig } from './config.js';
import { Key, keyCode, strokeForChar } from './keyboard.js';

/** Value types used by NP2's ini table (native/src/wasm/ini.h). */
const enum IniType { STR = 0, BOOL, BYTEARG, SINT8, SINT16, SINT32, UINT8, UINT16, UINT32, HEX8, HEX16, HEX32 }

// Emscripten module surface we use. Kept loose on purpose: the generated .d.ts
// is not part of the published API.
interface NP2Module {
  FS: any;
  HEAPU8: Uint8Array;
  HEAP8: Int8Array;
  HEAP16: Int16Array;
  HEAPU16: Uint16Array;
  HEAP32: Int32Array;
  HEAPU32: Uint32Array;
  ccall: (name: string, ret: string | null, argTypes: string[], args: unknown[]) => any;
  UTF8ToString: (ptr: number) => string;
  stringToUTF8: (s: string, ptr: number, max: number) => void;
  [fn: `_np2w_${string}`]: (...args: number[]) => number;
}

export interface Screen {
  width: number;
  height: number;
  /** Tightly packed RGBA, width * height * 4 bytes. A copy, safe to keep. */
  rgba: Uint8ClampedArray;
  /** Increments whenever NP2 redraws. */
  version: number;
}

export type DriveKind = 'fdd' | 'hdd';

export interface PC98Options {
  config?: Partial<MachineConfig>;
  /** PC-98 font bitmap. Defaults to the bundled Shinonome-based font.bmp. */
  font?: Uint8Array;
  /** Optional real ROMs and samples by file name (bios.rom, font.rom, sound.rom, itf.rom, 2608_bd.wav...). */
  bios?: Record<string, Uint8Array>;
  /** Emulated wall clock at power-on, ms since epoch in local time. Fix it for reproducible runs. */
  epochMs?: number;
  /** Called after the machine writes to a mounted disk image. */
  onDiskChange?: (name: string) => void;
  /** Called when the guest powers the machine off. */
  onExit?: () => void;
}

interface QueuedInput {
  /** Frame (np2w_frames) at which the event fires. */
  frame: number;
  apply: () => void;
}

const DISK_DIR = '/disks/';

function localNowMs(): number {
  const now = new Date();
  return now.getTime() - now.getTimezoneOffset() * 60_000;
}

async function loadAsset(url: URL): Promise<Uint8Array> {
  if (url.protocol === 'file:') {
    const { readFile } = await import('node:fs/promises');
    return new Uint8Array(await readFile(url));
  }
  const res = await fetch(url);
  if (!res.ok) throw new Error(`Failed to load ${url}: ${res.status}`);
  return new Uint8Array(await res.arrayBuffer());
}

/**
 * A PC-9801 machine. The host drives it explicitly: call runFrame() from a
 * render loop for real-time play, or step it from an agent for deterministic,
 * faster-than-real-time sessions.
 */
export class PC98 {
  readonly config: MachineConfig;
  private readonly m: NP2Module;
  private readonly ini: Record<string, unknown>;
  private readonly opts: PC98Options;
  private readonly queue: QueuedInput[] = [];
  private readonly mounted = new Map<string, string>(); // "fdd0" -> fs path
  private powered = true;

  private constructor(m: NP2Module, config: MachineConfig, ini: Record<string, unknown>, opts: PC98Options) {
    this.m = m;
    this.config = config;
    this.ini = ini;
    this.opts = opts;
  }

  static async create(opts: PC98Options = {}): Promise<PC98> {
    const config: MachineConfig = { ...DEFAULT_CONFIG, ...opts.config };
    const ini = toIni(config) as Record<string, unknown>;

    const factory = config.cpu === 'i386'
      // @ts-ignore generated by native/build.sh
      ? (await import('../wasm/np21.js')).default
      // @ts-ignore generated by native/build.sh
      : (await import('../wasm/np2.js')).default;

    const font = opts.font ?? await loadAsset(new URL('../wasm/font.bmp', import.meta.url));

    let self: PC98 | undefined;
    const m: NP2Module = await factory({
      print: () => {},
      printErr: (s: string) => console.warn('[np2]', s),
      getConfig: (pName: number, type: number, pValue: number, size: number) =>
        PC98.readIni(m, ini, pName, type, pValue, size),
      setConfig: () => {},
      onDiskChange: (pName: number) => self?.handleDiskChange(m.UTF8ToString(pName)),
      onExit: () => self?.handleExit(),
    });

    m.FS.mkdirTree('/np2/bios');
    m.FS.mkdirTree(DISK_DIR);
    m.FS.writeFile(FS_FONT, font);
    for (const [name, bytes] of Object.entries(opts.bios ?? {})) {
      m.FS.writeFile(FS_BIOS_DIR + name, bytes);
    }

    self = new PC98(m, config, ini, opts);
    if (m._np2w_init(opts.epochMs ?? localNowMs()) !== 0) {
      throw new Error('NP2 failed to initialize');
    }
    return self;
  }

  private static readIni(m: NP2Module, ini: Record<string, unknown>, pName: number, type: number, p: number, size: number) {
    const v = ini[m.UTF8ToString(pName)];
    if (v === undefined) return;
    switch (type) {
      case IniType.STR: m.stringToUTF8(String(v), p, size); break;
      case IniType.BOOL: m.HEAP8[p] = v ? 1 : 0; break;
      case IniType.BYTEARG: (v as number[]).forEach((b, i) => { if (i < size) m.HEAPU8[p + i] = b; }); break;
      case IniType.SINT8: m.HEAP8[p] = Number(v); break;
      case IniType.UINT8: case IniType.HEX8: m.HEAPU8[p] = Number(v); break;
      case IniType.SINT16: m.HEAP16[p >> 1] = Number(v); break;
      case IniType.UINT16: case IniType.HEX16: m.HEAPU16[p >> 1] = Number(v); break;
      case IniType.SINT32: m.HEAP32[p >> 2] = Number(v); break;
      case IniType.UINT32: case IniType.HEX32: m.HEAPU32[p >> 2] = Number(v); break;
    }
  }

  // ---- execution

  /** True until the guest powers off. reset() powers it back on. */
  get isPowered(): boolean { return this.powered; }

  /** Frames executed since power-on. */
  get frames(): number { return this.m._np2w_frames() >>> 0; }

  /** Disk sectors read or written since power-on: changes while the guest is loading. */
  get diskActivity(): number { return this.m._np2w_disk_activity() >>> 0; }

  /** Emulated milliseconds since power-on. */
  get elapsedMs(): number { return this.m._np2w_elapsed_ms_f(); }

  /** Runs one video frame (about 17.7 ms of emulated time in 400-line mode). */
  runFrame(draw = true): boolean {
    this.flushInput();
    const alive = this.m._np2w_run_frame(draw ? 1 : 0) === 1;
    if (!alive) this.powered = false;
    return alive;
  }

  /** Runs n frames, drawing only the last one. Returns the frames actually run. */
  runFrames(n: number): number {
    let i = 0;
    for (; i < n; i++) {
      if (!this.runFrame(i === n - 1)) break;
    }
    return i;
  }

  /** Runs until predicate() is true, checking after each frame. Returns whether it matched. */
  runUntil(predicate: (pc: PC98) => boolean, maxFrames: number): boolean {
    for (let i = 0; i < maxFrames; i++) {
      if (!this.runFrame(true)) return false;
      if (predicate(this)) return true;
    }
    return false;
  }

  reset(): void {
    this.queue.length = 0;
    this.m._np2w_key_release_all();
    this.m._np2w_reset();
    this.powered = true;
  }

  // ---- video

  get screenVersion(): number { return this.m._np2w_get_screen_version() >>> 0; }

  screen(): Screen {
    const width = this.m._np2w_get_screen_width();
    const height = this.m._np2w_get_screen_height();
    const ptr = this.m._np2w_get_screen_rgba();
    const rgba = new Uint8ClampedArray(this.m.HEAPU8.buffer.slice(ptr, ptr + width * height * 4));
    return { width, height, rgba, version: this.screenVersion };
  }

  /** Text VRAM decoded to UTF-8, one line per row. */
  textScreen(opts: { rows?: number; hideSecret?: boolean } = {}): string {
    const ptr = this.m._np2w_text_vram_utf8(opts.rows ?? 25, opts.hideSecret === false ? 0 : 1);
    return this.m.UTF8ToString(ptr);
  }

  // ---- audio

  get sampleRate(): number { return this.m._np2w_audio_rate(); }

  /** Interleaved stereo S16 PCM generated since the last call. */
  drainAudio(): Int16Array {
    const frames = this.m._np2w_audio_drain();
    const ptr = this.m._np2w_audio_buffer();
    return new Int16Array(this.m.HEAPU8.buffer.slice(ptr, ptr + frames * 4));
  }

  // ---- input

  keyDown(code: number): void { this.m._np2w_key(code, 1); }
  keyUp(code: number): void { this.m._np2w_key(code, 0); }
  releaseAllKeys(): void { this.m._np2w_key_release_all(); }

  /** Relative mouse motion in mickeys. */
  mouseMove(dx: number, dy: number): void { this.m._np2w_mouse_move(dx | 0, dy | 0); }
  mouseButtons(left: boolean, right: boolean): void { this.m._np2w_mouse_buttons(left ? 1 : 0, right ? 1 : 0); }

  /** Schedules fn to run before the frame that is `delay` frames from now. */
  schedule(delay: number, fn: () => void): void {
    this.queue.push({ frame: this.frames + delay, apply: fn });
    this.queue.sort((a, b) => a.frame - b.frame);
  }

  /** Number of scheduled input events not yet delivered. */
  get pendingInput(): number { return this.queue.length; }

  /**
   * Presses and releases a key (by name or scan code), optionally with modifiers.
   * Delivered over the next frames; run frames to let the guest see it.
   */
  pressKey(key: string | number, opts: { shift?: boolean; ctrl?: boolean; grph?: boolean; holdFrames?: number } = {}): void {
    const code = typeof key === 'number' ? key : keyCode(key);
    if (code === undefined) throw new Error(`Unknown PC-98 key: ${key}`);
    const hold = opts.holdFrames ?? 3;
    const mods: number[] = [];
    if (opts.shift) mods.push(Key.SHIFT);
    if (opts.ctrl) mods.push(Key.CTRL);
    if (opts.grph) mods.push(Key.GRPH);
    let t = this.lastQueuedFrameOffset();
    for (const mod of mods) this.schedule(t, () => this.keyDown(mod));
    if (mods.length) t += 1;
    this.schedule(t, () => this.keyDown(code));
    this.schedule(t + hold, () => this.keyUp(code));
    for (const mod of mods) this.schedule(t + hold + 1, () => this.keyUp(mod));
    // gap so consecutive strokes are seen as separate presses
    this.schedule(t + hold + 3, () => {});
  }

  /** Types ASCII text on the JIS layout ("\n" presses RETURN). */
  typeText(text: string, opts: { holdFrames?: number } = {}): void {
    for (const ch of text) {
      const stroke = strokeForChar(ch);
      if (!stroke) throw new Error(`Cannot type ${JSON.stringify(ch)} on the PC-98 keyboard`);
      this.pressKey(stroke.code, { shift: stroke.shift, holdFrames: opts.holdFrames });
    }
  }

  /** Leaves `frames` frames with no input after everything already queued. */
  queueGap(frames: number): void {
    this.schedule(this.lastQueuedFrameOffset() + frames, () => {});
  }

  private lastQueuedFrameOffset(): number {
    if (!this.queue.length) return 0;
    return Math.max(0, this.queue[this.queue.length - 1].frame - this.frames);
  }

  private flushInput(): void {
    const now = this.frames;
    while (this.queue.length && this.queue[0].frame <= now) {
      this.queue.shift()!.apply();
    }
  }

  // ---- disks

  /** Loads a disk image into the emulator's filesystem and mounts it. HDD changes apply on reset(). */
  insertDisk(kind: DriveKind, drive: number, name: string, bytes: Uint8Array): void {
    const path = DISK_DIR + name.replace(/[\/\\]/g, '_');
    this.m.FS.writeFile(path, bytes);
    this.mount(kind, drive, path);
  }

  ejectDisk(kind: DriveKind, drive: number): void {
    if (kind === 'fdd') this.m.ccall('diskdrv_setfddex', null, ['number', 'number', 'number', 'number'], [drive, 0, 0, 0]);
    else this.m.ccall('diskdrv_setsxsi', null, ['number', 'number'], [drive, 0]);
    this.mounted.delete(`${kind}${drive}`);
  }

  private mount(kind: DriveKind, drive: number, path: string): void {
    if (kind === 'fdd') this.m.ccall('diskdrv_setfddex', null, ['number', 'string', 'number', 'number'], [drive, path, 0, 0]);
    else this.m.ccall('diskdrv_setsxsi', null, ['number', 'string'], [drive, path]);
    this.mounted.set(`${kind}${drive}`, path);
  }

  /** Mounted images as { "fdd0": "name.hdm" }. */
  mountedDisks(): Record<string, string> {
    return Object.fromEntries([...this.mounted].map(([k, p]) => [k, p.slice(DISK_DIR.length)]));
  }

  /** Current bytes of a disk image, including the guest's writes. */
  readDisk(name: string): Uint8Array {
    return this.m.FS.readFile(DISK_DIR + name.replace(/[\/\\]/g, '_'));
  }

  private handleDiskChange(path: string): void {
    this.opts.onDiskChange?.(path.startsWith(DISK_DIR) ? path.slice(DISK_DIR.length) : path);
  }

  private handleExit(): void {
    this.powered = false;
    this.opts.onExit?.();
  }

  // ---- save states

  saveState(): Uint8Array {
    const path = '/np2/state.tmp';
    if (this.m.ccall('np2w_state_save', 'number', ['string'], [path]) !== 0) throw new Error('Failed to save state');
    const bytes: Uint8Array = this.m.FS.readFile(path);
    this.m.FS.unlink(path);
    return bytes;
  }

  /**
   * Restores a state. States reference disks by name rather than embedding
   * them, so `diskChanged` is true when a mounted image differs from the one
   * the state was saved with (it still loads).
   */
  loadState(bytes: Uint8Array): { diskChanged: boolean; warnings: boolean } {
    const path = '/np2/state.tmp';
    this.m.FS.writeFile(path, bytes);
    const ret: number = this.m.ccall('np2w_state_load', 'number', ['string'], [path]);
    this.m.FS.unlink(path);
    if (ret < 0) throw new Error('Failed to load state: not a compatible NP2 state');
    this.queue.length = 0;
    this.powered = true;
    return { diskChanged: (ret & 0x01) !== 0, warnings: (ret & 0x80) !== 0 };
  }

  // ---- memory

  /** Reads guest physical memory (first 2 MB: conventional, VRAM, BIOS areas). */
  readMemory(addr: number, length: number): Uint8Array {
    if (addr < 0 || addr + length > 0x200000) throw new RangeError('Address outside the first 2 MB');
    const base = this.m._np2w_mem_base();
    return this.m.HEAPU8.slice(base + addr, base + addr + length);
  }

  writeMemory(addr: number, bytes: Uint8Array): void {
    if (addr < 0 || addr + bytes.length > 0x200000) throw new RangeError('Address outside the first 2 MB');
    this.m.HEAPU8.set(bytes, this.m._np2w_mem_base() + addr);
  }

  /** The NP2 ini values this machine was booted with. */
  get iniValues(): Readonly<Record<string, unknown>> { return this.ini; }
}
